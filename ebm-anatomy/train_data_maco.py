def estimate_local_phase_epsilon(phase_tensor, sample_size=4096):
    sample_size = min(sample_size, phase_tensor.shape[0])
    phase_sample = phase_tensor[:sample_size].reshape(sample_size, -1).float().cpu()
    phase_sample = phase_sample - phase_sample.mean(dim=0, keepdim=True)
    covariance = phase_sample.T @ phase_sample / max(sample_size - 1, 1)
    eigvals = t.linalg.eigvalsh(covariance)
    return float(t.sqrt(t.clamp(eigvals.min(), min=1e-12)).item())

