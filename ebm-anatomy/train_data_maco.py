# --- MACO MODIF : sample_s_t opère maintenant sur la PHASE, pas sur les pixels ---
def sample_s_t(L, init_type, update_s_t_0=True, batch_size=config['batch_size']):

    def sample_phi_0():
        if init_type == 'persistent':
            mask = t.rand(batch_size, device=device) < RANDOMRATE
            indices = t.randperm(phi_t_0.shape[0], device=device)[:batch_size]
            persistent_samples = phi_t_0[indices]
            random_samples = sample_random_phase(batch_size)
            phi_0 = t.where(mask.view(-1, 1, 1, 1), persistent_samples, random_samples)
            sample_inds = indices.clone()
            return phi_0, sample_inds
        elif init_type == 'data':
            # phase initiale = phase CIFAR standardisée pré-calculée
            phi_0 = sample_q(batch_size=batch_size)
            return phi_0, None
        elif init_type in ('uniform', 'gaussian'):
            return sample_random_phase(batch_size), None
        else:
            raise RuntimeError('Invalid method for "init_type" (use "persistent", "data", "uniform", or "gaussian")')

    phi_0, phi_0_inds = sample_phi_0()
    phi_s_t = t.autograd.Variable(phi_0.clone(), requires_grad=True)
    r_s_t = t.zeros(1).to(device)

    for ell in range(L):
        f_val = f(phi_s_t)
        f_prime = t.autograd.grad(f_val.sum(), [phi_s_t])[0]   # gradient PAR RAPPORT A LA PHASE

        if LANGEVIN_SQUARED_NORMALISED:
            f_prime_norm = f_prime / (f_prime.view(f_prime.shape[0], -1).norm(dim=1).pow(2).view(-1, 1, 1, 1) + 1e-8)
        else:
            f_prime_norm = STEP_SIZE*f_prime

        # mise à jour Langevin sur la phase standardisée
        phi_s_t.data = phi_s_t.data + (-f_prime_norm + EPSILON * t.randn_like(phi_s_t))
        r_s_t += f_prime.view(f_prime.shape[0], -1).norm(dim=1).mean()

    if init_type == 'persistent' and update_s_t_0:
        phi_t_0.data[phi_0_inds] = phi_s_t.detach().data.clone()

    return phi_s_t.detach(), r_s_t.squeeze() / L


# --- MACO MODIF : langevin_grad (long-run) opère aussi sur la phase ---
def langevin_grad(f, phi_0_l, config, temp, batch_size):
    phi_s_t_l = t.autograd.Variable(phi_0_l.clone(), requires_grad=True)

    grads = t.zeros(config['num_longrun_steps'], batch_size)
    ens = t.zeros(config['num_longrun_steps'], batch_size)

    for ell in range(config['num_longrun_steps']):
        f_val = f(phi_s_t_l)
        en = f_val / temp
        ens[ell] = en.detach().cpu()
        grad = t.autograd.grad(en.sum(), [phi_s_t_l])[0]

        if LANGEVIN_SQUARED_NORMALISED:
            grad_norm = grad / (grad.view(grad.shape[0], -1).norm(dim=1).pow(2).view(-1, 1, 1, 1) + 1e-8)
        else:
            grad_norm = STEP_SIZE*grad

        if DST_SCALED:
            phi_s_t_l.data = phi_s_t_l.data + (-((EPSILON**2)/2) * grad_norm + EPSILON * t.randn_like(phi_s_t_l))
            grads[ell] = ((EPSILON**2)/2) * grad.view(grad.shape[0], -1).norm(dim=1).cpu()
        else:
            phi_s_t_l.data = phi_s_t_l.data + (-grad_norm + EPSILON * t.randn_like(phi_s_t_l))
            grads[ell] = grad.view(grad.shape[0], -1).norm(dim=1).cpu()


    return phi_s_t_l.detach(), ens, grads

def sample_s_tlongrun(f, config, device, init_type, batch_size):
    # --- MACO MODIF : init en phase, plus en pixels/uniforme/gaussien/fft ---
    if init_type in ('uniform', 'gaussian', 'fft'):
        phi_0_l = sample_random_phase(batch_size)
    else:
        raise RuntimeError('Invalid method for "init_type" (use "uniform", "gaussian", or "fft")')

    phi_final = langevin_grad(f, phi_0_l, config, temp, batch_size)[0]
    return phi_final.detach()


